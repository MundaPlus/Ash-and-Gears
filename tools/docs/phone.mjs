import { chromium, devices } from "@playwright/test";
const [base, outDir] = process.argv.slice(2);
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices["Pixel 7"] });
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(String(e)));
await p.goto(`${base}/?seed=phone-look`);
await p.waitForFunction(() => window.__game?.ready === true);
await p.evaluate(() => { window.__game.runTicks(2500); window.__game.camera.zoom = 1.6; });
await p.waitForTimeout(400);
await p.screenshot({ path: `${outDir}/p1-game.png` });
await p.getByTestId("tb-build").click();
await p.waitForTimeout(200);
await p.screenshot({ path: `${outDir}/p2-build.png` });
await p.getByTestId("tb-build").click();
await p.getByTestId("colonists").locator("button").first().click();
await p.waitForTimeout(300);
await p.screenshot({ path: `${outDir}/p3-pawn.png` });
await p.keyboard.press("Escape");
await p.getByTestId("menu-btn").click();
await p.waitForTimeout(200);
await p.screenshot({ path: `${outDir}/p4-menu.png` });
console.log("errors:", errs);
await b.close();
